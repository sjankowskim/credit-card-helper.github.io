import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Resolve __dirname equivalent in ES Modules
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const cardsDir = path.join(__dirname, '../src/app/core/data/cards');
const imagesDir = path.join(__dirname, '../public/images/cards');
const indexFile = path.join(cardsDir, 'index.ts');

/**
 * Recursively find files with the given extension
 */
function getFiles(dir, extension) {
  return fs.readdirSync(dir).flatMap((file) => {
    const filePath = path.join(dir, file);
    if (fs.statSync(filePath).isDirectory()) return getFiles(filePath, extension);
    return file.endsWith(extension) ? [filePath] : [];
  });
}

const allFiles = getFiles(cardsDir, '.ts').filter((file) => path.basename(file) !== 'index.ts');

const imports = [];
const exports = [];
const seenVarNames = new Map();
const seenCardIds = new Map();
/**
 * Card artwork mirrors the card files: cards/chase/freedom.ts -> public/images/cards/chase/freedom.png.
 * Alternate designs add a number: freedom-2.png, freedom-3.png. The plain file is the default design.
 * imagesByCardPath maps 'chase/freedom' to its image URLs, default first.
 */
const imagesByCardPath = new Map();
for (const image of getFiles(imagesDir, '.png')) {
  const relativeImage = path.relative(imagesDir, image).replace(/\\/g, '/').replace(/\.png$/, '');
  const [, base, variant] = /^(.*?)(?:-(\d+))?$/.exec(relativeImage);
  const images = imagesByCardPath.get(base) ?? [];
  images.push({ order: variant ? Number(variant) : 1, url: `/images/cards/${relativeImage}.png` });
  imagesByCardPath.set(base, images);
}

/** [card id, image URLs] for the cards that have artwork */
const cardImages = [];
/** [card id, id of the card whose artwork it reuses, card file path] from `imageOf` */
const borrowedImages = [];

function fail(message) {
  console.error(`\x1b[31m[Card Indexer]\x1b[0m ${message}`);
  process.exit(1);
}

allFiles.forEach((filePath) => {
  const relativePath = path
    .relative(cardsDir, filePath)
    .replace(/\\/g, '/')
    .replace(/\.ts$/, '');

  const fileName = path.basename(filePath, '.ts');
  const varName = fileName.toUpperCase().replace(/-/g, '_');

  if (seenVarNames.has(varName)) {
    console.error(
      `\x1b[31m[Card Indexer]\x1b[0m ${relativePath}.ts and ${seenVarNames.get(varName)}.ts both export ${varName}. Rename one file.`
    );
    process.exit(1);
  }
  seenVarNames.set(varName, relativePath);

  // Catalog checks (category ids are already checked by the CategoryId type)
  const source = fs.readFileSync(filePath, 'utf8');
  const cardId = /^  id: '([^']+)'/m.exec(source)?.[1];
  if (!cardId) {
    fail(`${relativePath}.ts has no top-level card id.`);
  } else if (seenCardIds.has(cardId)) {
    fail(`${relativePath}.ts and ${seenCardIds.get(cardId)}.ts both use the card id '${cardId}'.`);
  }
  seenCardIds.set(cardId, relativePath);

  const images = imagesByCardPath.get(relativePath);
  const imageOf = /^  imageOf: '([^']+)'/m.exec(source)?.[1];
  if (imageOf) {
    if (images) console.warn(`\x1b[33m[Card Indexer]\x1b[0m ${relativePath}.ts has its own image and imageOf; the imageOf is ignored`);
    else borrowedImages.push([cardId, imageOf, relativePath]);
  }
  if (images) {
    cardImages.push([cardId, images.sort((a, b) => a.order - b.order).map((image) => image.url)]);
  } else if (!imageOf) {
    console.warn(`\x1b[33m[Card Indexer]\x1b[0m No image for ${relativePath}.ts; add public/images/cards/${relativePath}.png`);
  }

  imports.push(`import { ${varName} } from './${relativePath}';`);
  exports.push(`  ${varName},`);
});

// Cards that reuse another card's artwork
const imagesById = new Map(cardImages);
for (const [cardId, imageOf, relativePath] of borrowedImages) {
  const images = imagesById.get(imageOf);
  if (images) cardImages.push([cardId, images]);
  else console.warn(`\x1b[33m[Card Indexer]\x1b[0m ${relativePath}.ts uses the image of '${imageOf}', which has none`);
}

const content = `// ============================================================================
// AUTO-GENERATED BARREL EXPORT - DO NOT EDIT DIRECTLY
// Generated by scripts/generate-card-index.mjs
// ============================================================================
import { Card } from '../../models/card.model';

${imports.join('\n')}

export const ALL_CARDS: Card[] = [
${exports.join('\n')}
];

export const CARD_MAP = new Map<string, Card>(
  ALL_CARDS.map(card => [card.id, card])
);

/** Image URLs by card id, default design first; artwork lives at the card file's path under public/images/cards */
export const CARD_IMAGE_URLS = new Map<string, string[]>([
${cardImages.map(([id, urls]) => `  ['${id}', [${urls.map((url) => `'${url}'`).join(', ')}]],`).join('\n')}
]);
`;

// Images that no card file points to (e.g. left behind after renaming a card file)
const cardPaths = new Set(seenVarNames.values());
for (const [base, images] of imagesByCardPath) {
  if (!cardPaths.has(base)) {
    for (const image of images) {
      console.warn(`\x1b[33m[Card Indexer]\x1b[0m public${image.url} doesn't match any card file`);
    }
  }
}

fs.writeFileSync(indexFile, content);
console.log(`\x1b[32m[Card Indexer]\x1b[0m Successfully indexed ${allFiles.length} card files in cards/index.ts`);