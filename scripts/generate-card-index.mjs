import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Resolve __dirname equivalent in ES Modules
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const cardsDir = path.join(__dirname, '../src/app/core/data/cards');
const indexFile = path.join(cardsDir, 'index.ts');

/**
 * Recursively find all .ts files in the cards directory
 */
function getCardFiles(dir) {
  let results = [];
  const list = fs.readdirSync(dir);

  list.forEach((file) => {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);

    if (stat && stat.isDirectory()) {
      results = results.concat(getCardFiles(filePath));
    } else if (file.endsWith('.ts') && file !== 'index.ts') {
      results.push(filePath);
    }
  });

  return results;
}

const allFiles = getCardFiles(cardsDir);

const imports = [];
const exports = [];
const seenVarNames = new Map();

allFiles.forEach((filePath) => {
  const relativePath = path
    .relative(cardsDir, filePath)
    .replace(/\\/g, '/')
    .replace(/\.ts$/, '');

  const fileName = path.basename(filePath, '.ts');
  const varName = fileName.toUpperCase().replace(/-/g, '_');

  if (seenVarNames.has(varName)) {
    console.error(
      `\x1b[31m[Card Indexer]\x1b[0m ${relativePath}.ts and ${seenVarNames.get(varName)}.ts both export ${varName}. Rename one file.`
    );
    process.exit(1);
  }
  seenVarNames.set(varName, relativePath);

  imports.push(`import { ${varName} } from './${relativePath}';`);
  exports.push(`  ${varName},`);
});

const content = `// ============================================================================
// AUTO-GENERATED BARREL EXPORT - DO NOT EDIT DIRECTLY
// Generated by scripts/generate-card-index.mjs
// ============================================================================
import { Card } from '../../models/card.model';

${imports.join('\n')}

export const ALL_CARDS: Card[] = [
${exports.join('\n')}
];

export const CARD_MAP = new Map<string, Card>(
  ALL_CARDS.map(card => [card.id, card])
);
`;

fs.writeFileSync(indexFile, content);
console.log(`\x1b[32m[Card Indexer]\x1b[0m Successfully indexed ${allFiles.length} card files in cards/index.ts`);